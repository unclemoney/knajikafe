FULL_PUNCT = re.compile(r"[，；“”！？]|——")
KANA = re.compile(r"[ぁ-ヿ]")
CJK = re.compile(r"[一-鿿]")

def needs_translation(line):
    if not CJK.search(line):
        return False
    if any(c in SIMPLIFIED for c in line):
        return True
    if FULL_PUNCT.search(line):
        return True
    if not KANA.search(line):
        return True
    return False

occ = {}
segs = []
for f in sorted(glob.glob("markdown/*/*.md")):
    if os.path.basename(f).startswith("_"):
        continue
    for i, line in enumerate(open(f, encoding="utf-8").read().split("\n")):
        s = line.strip()
        if s and needs_translation(s):
            if s not in occ:
                occ[s] = len(segs)
                segs.append(s)
with open("work/segments_md2.jsonl", "w", encoding="utf-8") as fh:
    for i, s in enumerate(segs):
        fh.write(json.dumps({"id": i, "text": s}, ensure_ascii=False) + "\n")

# build map id -> occurrences
idmap = {s: i for i, s in enumerate(segs)}
lmap = {}
for f in sorted(glob.glob("markdown/*/*.md")):
    if os.path.basename(f).startswith("_"):
        continue
    for i, line in enumerate(open(f, encoding="utf-8").read().split("\n")):
        s = line.strip()
        if s in idmap:
            lmap.setdefault(idmap[s], []).append([f, i + 1])
with open("work/md2_line_map.json", "w", encoding="utf-8") as fh:
    json.dump({str(k): v for k, v in lmap.items()}, fh, ensure_ascii=False)
total_chars = sum(len(s) for s in segs)
print("unique remaining lines:", len(segs), "chars:", total_chars, "occurrences:", sum(len(v) for v in lmap.values()))
